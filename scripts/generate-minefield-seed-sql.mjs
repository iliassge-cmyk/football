// Regenerates supabase/seed-minefield-challenges.sql from src/data/minefield_daily.json.
// Run this after regenerating minefield_daily.json (scripts/generate-minefield-daily.mjs):
//   node scripts/generate-minefield-seed-sql.mjs
// The output is plain SQL meant to be pasted into the Supabase SQL Editor —
// no terminal/CLI access to the project needed, just copy-paste-run.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const days = JSON.parse(readFileSync(path.join(__dirname, '../src/data/minefield_daily.json'), 'utf8'))

function sqlString(value) {
  return value == null ? 'NULL' : `'${String(value).replace(/'/g, "''")}'`
}

let sql = `-- Auto-generated by scripts/generate-minefield-seed-sql.mjs from src/data/minefield_daily.json.
-- Do not hand-edit — edit the JSON and regenerate instead.
-- Safe to re-run: upserts by date (the table's primary key).
-- Paste this whole file into the Supabase SQL Editor and run it, after
-- supabase/schema.sql has already been applied.

`

for (const d of days) {
  const tilesJson = JSON.stringify(d.tiles).replace(/'/g, "''")
  sql += `insert into minefield_challenges (date, title, criteria_description, tiles, source, verified_date)\n`
  sql += `values (${sqlString(d.date)}, ${sqlString(d.title)}, ${sqlString(d.criteria_description)}, '${tilesJson}'::jsonb, ${sqlString(d.source)}, ${sqlString(d.verified_date)})\n`
  sql += `on conflict (date) do update set title = excluded.title, criteria_description = excluded.criteria_description, tiles = excluded.tiles, source = excluded.source, verified_date = excluded.verified_date;\n\n`
}

const outPath = path.join(__dirname, '../supabase/seed-minefield-challenges.sql')
writeFileSync(outPath, sql)
console.log(`Wrote ${days.length} rows to ${outPath}`)
