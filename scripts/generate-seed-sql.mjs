// Regenerates supabase/seed-daily-challenges.sql from src/data/daily_top10.json.
// Run this after adding/editing days in daily_top10.json:
//   node scripts/generate-seed-sql.mjs
// The output is plain SQL meant to be pasted into the Supabase SQL Editor —
// no terminal/CLI access to the project needed, just copy-paste-run.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const days = JSON.parse(readFileSync(path.join(__dirname, '../src/data/daily_top10.json'), 'utf8'))

function sqlString(value) {
  return value == null ? 'NULL' : `'${String(value).replace(/'/g, "''")}'`
}

let sql = `-- Auto-generated by scripts/generate-seed-sql.mjs from src/data/daily_top10.json.
-- Do not hand-edit — edit the JSON and regenerate instead.
-- Safe to re-run: upserts by date (the table's primary key).
-- Paste this whole file into the Supabase SQL Editor and run it, after
-- supabase/schema.sql has already been applied.

`

for (const d of days) {
  const entriesJson = JSON.stringify(d.entries).replace(/'/g, "''")
  sql += `insert into daily_challenges (date, title, entries, source_primary, source_secondary, verified_date)\n`
  sql += `values (${sqlString(d.date)}, ${sqlString(d.title)}, '${entriesJson}'::jsonb, ${sqlString(d.source_primary)}, ${sqlString(d.source_secondary)}, ${sqlString(d.verified_date)})\n`
  sql += `on conflict (date) do update set title = excluded.title, entries = excluded.entries, source_primary = excluded.source_primary, source_secondary = excluded.source_secondary, verified_date = excluded.verified_date;\n\n`
}

const outPath = path.join(__dirname, '../supabase/seed-daily-challenges.sql')
writeFileSync(outPath, sql)
console.log(`Wrote ${days.length} rows to ${outPath}`)
